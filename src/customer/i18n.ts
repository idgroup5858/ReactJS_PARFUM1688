export const DICTS: Record<Lang, Dict> = { ru, uz }

export function useLang(): Lang {
  return useCustomer().lang
}

export function useT(): Dict {
  return DICTS[useLang()]
}

/** Ikki tilli qiymatdan joriy tildagisi. */
export function useLoc(): (value: Localized) => string {
  const lang = useLang()
  return (value) => value[lang] || value.ru
}

/** "519 000 сум" */
export function money(value: number, t: Dict): string {
  return `${formatNumber(value)}${NBSP}${t.common.sum}`
}

/** "100 г" */
export function grams(value: number, t: Dict): string {
  return `${formatNumber(value)}${NBSP}${t.common.g}`
}
