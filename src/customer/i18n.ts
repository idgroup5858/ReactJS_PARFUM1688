const ruPlural = new Intl.PluralRules('ru')

/** Ruscha son bilan ot: 1 аромат, 2 аромата, 5 ароматов, 21 аромат. */
function ruCount(n: number, one: string, few: string, many: string): string {
  const form = ruPlural.select(n)
  return `${formatNumber(n)} ${form === 'one' ? one : form === 'few' ? few : many}`
}

/** Narx oralig'i yorlig'i: qiymatlar tayyor ("3 000 сум"), bittasi bo'lmasligi mumkin. */
